"""
Compare the NucleusKit and Prime references case by case and write
``tests/references/DIVERGENCES.md``.

The report measures, on synthetic data, every difference between the two current systems.
Each case lists the Phase 1 decisions (D1–D22) it targets; the decisions say which side
the core must reproduce. Differences are reported with the same tolerance as the
non-regression tests, so "identical" means equal within rtol 1e-6, atol 1e-9.

Usage: python tools/report_divergences.py

Author(s):
    RE-AK Technologies Inc., Fall 2026
"""

from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import refkit  # noqa: E402


def _cell(text: str) -> str:
    """Markdown table cells must not contain pipes or newlines."""
    return str(text).replace("|", "/").replace("\n", " ")


def _run_errors(path: str) -> list[str]:
    report = os.path.join(path, "reference_run.json")
    if not os.path.isfile(report):
        return ["no run report"]
    with open(report, encoding="utf-8") as fh:
        run = json.load(fh)
    return [f"{s['step']}: {s.get('error', '')}" for s in run["steps"] if s["status"] != "ok"]


def _emotion_summary(path: str) -> dict | None:
    file = os.path.join(path, "results__Emotions.csv.gz")
    if not os.path.isfile(file):
        return None
    df = refkit.load_output(file)
    values = df.drop(columns=["Timestamp"])
    null_rows = int(values.isna().all(axis=1).sum())
    valid = ~values.isna().all(axis=1)
    labels = values[valid].idxmax(axis=1).reindex(values.index)
    return {"rows": len(df), "null_rows": null_rows, "labels": labels}


def _emotion_line(nk_dir: str, prime_dir: str) -> str | None:
    a, b = _emotion_summary(nk_dir), _emotion_summary(prime_dir)
    if not a or not b:
        return None
    n = min(len(a["labels"]), len(b["labels"]))
    la, lb = a["labels"].iloc[:n], b["labels"].iloc[:n]
    both = la.notna() & lb.notna()
    agree = float((la[both] == lb[both]).mean() * 100) if both.any() else float("nan")
    return (
        f"Emotions.csv: NK {a['rows']} rows ({a['null_rows']} null), Prime {b['rows']} rows ({b['null_rows']} null); "
        f"dominant emotion agrees on {agree:.1f} % of the rows valid on both sides"
    )


def main() -> int:
    with open(os.path.join(refkit.REFERENCES_DIR, "manifest.json"), encoding="utf-8") as fh:
        manifest = json.load(fh)
    nk_commit = manifest["systems"]["nk"]["commit"][:7]
    prime_commit = manifest["systems"]["prime"]["commit"][:7]
    lines = [
        "# NucleusKit against Prime: measured divergences",
        "",
        "Generated by `tools/report_divergences.py` from the references in this folder. Do not edit by hand.",
        "",
        f"- NucleusKit: `{nk_commit}`, Prime: `{prime_commit}`, recorded on {manifest['recorded_on']}.",
        '- Tolerance: rtol 1e-6, atol 1e-9 (same as the non-regression tests). "Identical" means equal within it.',
        "- Which side the core must reproduce is set by the Phase 1 decisions (D1–D22), not by this report.",
        "",
        "## Summary",
        "",
        "| Case | Targets | Model | Identical outputs | Differing outputs | Only one side | Step errors |",
        "|---|---|---|---|---|---|---|",
    ]
    details = []
    for case_name, info in manifest["cases"].items():
        for model in refkit.MODELS:
            nk_dir = refkit.reference_dir("nk", model, case_name)
            prime_dir = refkit.reference_dir("prime", model, case_name)
            if not (os.path.isdir(nk_dir) and os.path.isdir(prime_dir)):
                continue
            outputs = refkit.FULL_OUTPUTS if model == refkit.PRIMARY_MODEL else refkit.EMOTION_OUTPUTS
            diffs = refkit.compare_dirs(nk_dir, prime_dir, outputs=outputs)
            present = {
                rel
                for rel in outputs
                if any(
                    os.path.isfile(os.path.join(d, rel.replace("/", "__") + ext))
                    for d in (nk_dir, prime_dir)
                    for ext in ("", ".gz")
                )
            }
            only_one = sorted({d.output for d in diffs if d.kind == "missing"})
            differing = sorted({d.output for d in diffs if d.kind != "missing"})
            identical = sorted(present - set(only_one) - set(differing))
            errors = [f"NK {e}" for e in _run_errors(nk_dir)] + [f"Prime {e}" for e in _run_errors(prime_dir)]
            short = model.replace("classical-emotion-", "")
            lines.append(
                f"| {case_name} | {', '.join(info['targets'])} | {short} | {len(identical)} | {len(differing)} | "
                f"{len(only_one)} | {len(errors)} |"
            )

            block = [
                f"### {case_name}, model {short}",
                "",
                f"{_cell(info['description'])}. Targets: {', '.join(info['targets'])}.",
                "",
            ]
            emo = _emotion_line(nk_dir, prime_dir)
            if emo:
                block += [f"- {emo}"]
            if identical:
                block += [f"- Identical: {', '.join('`' + p + '`' for p in identical)}"]
            if only_one:
                for d in diffs:
                    if d.kind == "missing":
                        side = "NK" if d.detail == "only in first" else "Prime"
                        block += [f"- Only {side} writes `{d.output}`"]
            if errors:
                block += [f"- Step error: {e}" for e in errors]
            rows = [d for d in diffs if d.kind not in ("missing",)]
            if rows:
                block += ["", "| Output | Difference | Max abs diff |", "|---|---|---|"]
                for d in rows:
                    max_abs = d.stats.get("max_abs")
                    block.append(
                        f"| `{d.output}` | {_cell(d.detail)} | {'' if max_abs is None else f'{max_abs:.4g}'} |"
                    )
            details += block + [""]
    lines += ["", "## Details", ""] + details
    path = os.path.join(refkit.REFERENCES_DIR, "DIVERGENCES.md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
